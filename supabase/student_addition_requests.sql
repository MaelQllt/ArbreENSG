-- À exécuter une fois dans Supabase > SQL Editor (script idempotent).
-- Propositions « Une personne manque » envoyées depuis le site : un visiteur
-- signale un étudiant absent de l'arbre (nom, promo, parrain éventuel).
-- Comme pour les propositions de liens, les visiteurs ne peuvent que créer une
-- demande via la fonction dédiée ; seuls les superadmins les consultent et les
-- traitent. Nécessite supabase/family_link_requests.sql (limite d'e-mails partagée).

create table if not exists public.student_addition_requests (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  promo integer not null,
  code text not null default '',
  parent_id text,
  parent_name text,
  message text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  email_claimed_at timestamptz,
  email_sent_at timestamptz
);

create index if not exists student_addition_requests_status_created_idx
  on public.student_addition_requests (status, created_at desc);

alter table public.student_addition_requests enable row level security;
revoke all on public.student_addition_requests from anon, authenticated;
grant select, insert, update, delete on public.student_addition_requests to service_role;

create or replace function public.submit_student_addition_request(
  p_first_name text,
  p_last_name text,
  p_promo integer,
  p_code text default '',
  p_parent_id text default null,
  p_parent_name text default null,
  p_message text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_first_name text := regexp_replace(coalesce(trim(p_first_name), ''), '\s+', ' ', 'g');
  v_last_name text := upper(regexp_replace(coalesce(trim(p_last_name), ''), '\s+', ' ', 'g'));
  v_code text := upper(coalesce(trim(p_code), ''));
  v_parent_id text := nullif(trim(coalesce(p_parent_id, '')), '');
  v_parent_name text := nullif(trim(coalesce(p_parent_name, '')), '');
  clean_message text := coalesce(trim(p_message), '');
  paris_now timestamp := now() at time zone 'Europe/Paris';
  current_promo integer := extract(year from paris_now)::integer
    - case when extract(month from paris_now) < 9 then 1 else 0 end;
  existing_request public.student_addition_requests%rowtype;
  inserted_request public.student_addition_requests%rowtype;
begin
  if v_first_name = '' or v_last_name = '' then
    raise exception 'Indique le prénom et le nom.' using errcode = '22023';
  end if;
  if length(v_first_name) > 100 or length(v_last_name) > 100 or length(clean_message) > 1500
    or length(coalesce(v_parent_id, '')) > 120 or length(coalesce(v_parent_name, '')) > 200 then
    raise exception 'La demande est trop longue.' using errcode = '22023';
  end if;
  if p_promo is null or p_promo < 1990 or p_promo > current_promo then
    raise exception 'Choisis une année de promo valide.' using errcode = '22023';
  end if;
  if v_code not in ('', 'ING', 'LG', 'M') then
    raise exception 'Formation inconnue.' using errcode = '22023';
  end if;
  if (v_parent_id is null) <> (v_parent_name is null) then
    raise exception 'Parrain ou marraine incomplet.' using errcode = '22023';
  end if;

  -- Garde-fou contre un envoi massif depuis le formulaire public.
  if (select count(*) from public.student_addition_requests r where r.status = 'pending') >= 300 then
    raise exception 'Trop de demandes en attente, réessaie plus tard.' using errcode = 'P0001';
  end if;

  -- Une seule demande en attente par personne (même prénom et même nom).
  perform pg_advisory_xact_lock(hashtextextended('student:' || lower(v_first_name || ' ' || v_last_name), 0));
  select * into existing_request
  from public.student_addition_requests r
  where r.status = 'pending'
    and lower(r.first_name) = lower(v_first_name)
    and lower(r.last_name) = lower(v_last_name)
  order by r.created_at, r.id
  limit 1;
  if found then
    return jsonb_build_object('id', existing_request.id, 'created_at', existing_request.created_at, 'duplicate', true);
  end if;

  insert into public.student_addition_requests (
    first_name, last_name, promo, code, parent_id, parent_name, message
  ) values (
    v_first_name, v_last_name, p_promo, v_code, v_parent_id, v_parent_name, clean_message
  ) returning * into inserted_request;

  return jsonb_build_object('id', inserted_request.id, 'created_at', inserted_request.created_at, 'duplicate', false);
end;
$$;

create or replace function public.list_student_addition_requests()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if auth.uid() is null or not exists (
    select 1 from public.superadmins s where s.user_id = auth.uid()
  ) then
    raise exception 'Accès réservé au superadmin.' using errcode = '42501';
  end if;

  select coalesce(
    jsonb_agg(to_jsonb(r) order by (r.status = 'pending') desc, r.created_at desc),
    '[]'::jsonb
  ) into result
  from public.student_addition_requests r;

  return result;
end;
$$;

create or replace function public.update_student_addition_request(
  p_request_id bigint,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_request public.student_addition_requests%rowtype;
begin
  if auth.uid() is null or not exists (
    select 1 from public.superadmins s where s.user_id = auth.uid()
  ) then
    raise exception 'Accès réservé au superadmin.' using errcode = '42501';
  end if;

  if p_status is null or p_status not in ('pending', 'resolved', 'dismissed') then
    raise exception 'Statut de demande invalide.' using errcode = '22023';
  end if;

  update public.student_addition_requests r
    set status = p_status,
        reviewed_at = case when p_status = 'pending' then null else now() end,
        reviewed_by = case when p_status = 'pending' then null else auth.uid() end
    where r.id = p_request_id
    returning * into updated_request;

  if not found then
    raise exception 'Cette demande n’existe plus.' using errcode = 'P0002';
  end if;

  return to_jsonb(updated_request);
end;
$$;

create or replace function public.delete_student_addition_request(p_request_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  deleted_request_id bigint;
begin
  if auth.uid() is null or not exists (
    select 1 from public.superadmins s where s.user_id = auth.uid()
  ) then
    raise exception 'Accès réservé au superadmin.' using errcode = '42501';
  end if;

  delete from public.student_addition_requests r
    where r.id = p_request_id
    returning r.id into deleted_request_id;

  if not found then
    raise exception 'Cette demande n’existe plus.' using errcode = 'P0002';
  end if;

  return deleted_request_id;
end;
$$;

-- Réservé à la fonction Edge qui envoie l'e-mail : une seule notification par
-- demande, et la même limite horaire que les propositions de liens.
create or replace function public.claim_student_addition_request_email(p_request_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed_request public.student_addition_requests%rowtype;
  emails_in_window integer;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Accès réservé au service d’envoi.' using errcode = '42501';
  end if;

  update public.student_addition_requests r
    set email_claimed_at = now()
    where r.id = p_request_id
      and r.email_sent_at is null
      and (r.email_claimed_at is null or r.email_claimed_at < now() - interval '10 minutes')
    returning * into claimed_request;

  if not found then
    return null;
  end if;

  insert into public.family_link_request_email_rate_limit as limits (
    id, window_started_at, sent_count
  ) values (true, now(), 1)
  on conflict (id) do update
    set window_started_at = case
          when limits.window_started_at <= now() - interval '1 hour' then now()
          else limits.window_started_at
        end,
        sent_count = case
          when limits.window_started_at <= now() - interval '1 hour' then 1
          else limits.sent_count + 1
        end
  returning sent_count into emails_in_window;

  if emails_in_window > 10 then
    update public.student_addition_requests r
      set email_claimed_at = null
      where r.id = p_request_id and r.email_sent_at is null;
    raise exception 'Limite horaire de notifications atteinte.' using errcode = 'P0001';
  end if;

  return to_jsonb(claimed_request);
end;
$$;

create or replace function public.mark_student_addition_request_email_sent(p_request_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Accès réservé au service d’envoi.' using errcode = '42501';
  end if;

  update public.student_addition_requests r
    set email_sent_at = now(),
        email_claimed_at = null
    where r.id = p_request_id
      and r.email_sent_at is null
      and r.email_claimed_at is not null;

  return found;
end;
$$;

create or replace function public.release_student_addition_request_email(p_request_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Accès réservé au service d’envoi.' using errcode = '42501';
  end if;

  update public.student_addition_requests r
    set email_claimed_at = null
    where r.id = p_request_id and r.email_sent_at is null;

  return found;
end;
$$;

