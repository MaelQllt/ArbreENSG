-- À exécuter une fois dans Supabase > SQL Editor après family_link_requests.sql.
-- Une relation ne peut avoir qu'une seule proposition en attente.
-- Les messages complémentaires sont conservés avec cette proposition et
-- signalés séparément au BDE, sans créer une seconde carte de requête.

begin;

create table if not exists public.family_link_request_reports (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.family_link_requests(id) on delete cascade,
  message text not null,
  created_at timestamptz not null default now(),
  email_claimed_at timestamptz,
  email_sent_at timestamptz,
  constraint family_link_request_reports_message_length check (length(message) <= 1500)
);

alter table public.family_link_request_reports enable row level security;
revoke all on public.family_link_request_reports from anon, authenticated;

create index if not exists family_link_request_reports_request_created_idx
  on public.family_link_request_reports (request_id, created_at asc);

-- Regroupe d'éventuelles propositions déjà en double : la plus ancienne reste
-- la proposition principale et les messages distincts sont conservés dessous.
with ranked as (
  select
    r.id,
    first_value(r.id) over (partition by r.parent_id, r.child_id order by r.created_at, r.id) as primary_id,
    row_number() over (partition by r.parent_id, r.child_id order by r.created_at, r.id) as position
  from public.family_link_requests r
  where r.status = 'pending'
), duplicate_messages as (
  select distinct on (ranked.primary_id, lower(trim(duplicate.message)))
    ranked.primary_id,
    trim(duplicate.message) as message,
    duplicate.created_at
  from ranked
  join public.family_link_requests primary_request on primary_request.id = ranked.primary_id
  join public.family_link_requests duplicate on duplicate.id = ranked.id
  where ranked.position > 1
    and nullif(trim(duplicate.message), '') is not null
    and lower(trim(duplicate.message)) <> lower(trim(primary_request.message))
    and not exists (
      select 1 from public.family_link_request_reports report
      where report.request_id = ranked.primary_id
        and lower(trim(report.message)) = lower(trim(duplicate.message))
    )
  order by ranked.primary_id, lower(trim(duplicate.message)), duplicate.created_at
)
insert into public.family_link_request_reports (request_id, message, created_at)
select primary_id, message, created_at from duplicate_messages;

with ranked as (
  select
    r.id,
    first_value(r.id) over (partition by r.parent_id, r.child_id order by r.created_at, r.id) as primary_id,
    row_number() over (partition by r.parent_id, r.child_id order by r.created_at, r.id) as position
  from public.family_link_requests r
  where r.status = 'pending'
)
update public.family_link_request_reports report
set request_id = ranked.primary_id
from ranked
where ranked.position > 1
  and report.request_id = ranked.id;

with ranked as (
  select
    r.id,
    row_number() over (partition by r.parent_id, r.child_id order by r.created_at, r.id) as position
  from public.family_link_requests r
  where r.status = 'pending'
)
delete from public.family_link_requests request
using ranked
where request.id = ranked.id and ranked.position > 1;

create unique index if not exists family_link_requests_one_pending_relation_idx
  on public.family_link_requests (parent_id, child_id)
  where status = 'pending';

create or replace function public.submit_family_link_request(
  p_child_id text,
  p_child_name text,
  p_parent_id text,
  p_parent_name text,
  p_message text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  inserted_request public.family_link_requests%rowtype;
  existing_request public.family_link_requests%rowtype;
  added_report public.family_link_request_reports%rowtype;
  existing_report public.family_link_request_reports%rowtype;
  clean_message text := coalesce(trim(p_message), '');
begin
  if nullif(trim(p_child_id), '') is null
    or nullif(trim(p_parent_id), '') is null
    or nullif(trim(p_child_name), '') is null
    or nullif(trim(p_parent_name), '') is null
    or trim(p_child_id) = trim(p_parent_id) then
    raise exception 'Choisis deux étudiants différents.' using errcode = '22023';
  end if;

  if length(trim(p_child_id)) > 120
    or length(trim(p_parent_id)) > 120
    or length(trim(p_child_name)) > 200
    or length(trim(p_parent_name)) > 200
    or length(clean_message) > 1500 then
    raise exception 'La demande est trop longue.' using errcode = '22023';
  end if;

  -- Sérialise deux envois simultanés portant sur le même lien dirigé.
  perform pg_advisory_xact_lock(hashtextextended(trim(p_parent_id) || '>' || trim(p_child_id), 0));

  select * into existing_request
  from public.family_link_requests r
  where r.parent_id = trim(p_parent_id)
    and r.child_id = trim(p_child_id)
    and r.status = 'pending'
  order by r.created_at, r.id
  limit 1
  for update;

  if found then
    if clean_message <> '' then
      select * into existing_report
      from public.family_link_request_reports report
      where report.request_id = existing_request.id
        and lower(trim(report.message)) = lower(clean_message)
      order by report.created_at, report.id
      limit 1;

      if not found and (
        lower(trim(existing_request.message)) <> lower(clean_message)
        or existing_request.email_sent_at is null
      ) then
        insert into public.family_link_request_reports (request_id, message)
        values (existing_request.id, clean_message)
        returning * into added_report;
      else
        added_report := existing_report;
      end if;
    end if;

    return jsonb_build_object(
      'id', existing_request.id,
      'created_at', existing_request.created_at,
      'duplicate', true,
      'message_received', clean_message <> '' and (
        added_report.id is not null or existing_report.id is not null
        or lower(trim(existing_request.message)) = lower(clean_message)
      ),
      'message_already_sent', (
        existing_report.id is not null and existing_report.email_sent_at is not null
      ) or (
        lower(trim(existing_request.message)) = lower(clean_message)
        and existing_request.email_sent_at is not null
      ),
      'report_id', case
        when added_report.id is not null and added_report.email_sent_at is null then added_report.id
        when existing_report.id is not null and existing_report.email_sent_at is null then existing_report.id
        else null
      end
    );
  end if;

  select * into existing_request
  from public.family_link_requests r
  where r.parent_id = trim(p_parent_id)
    and r.child_id = trim(p_child_id)
    and r.status = 'resolved'
  order by r.reviewed_at desc nulls last, r.id desc
  limit 1;

  if found then
    return jsonb_build_object(
      'id', existing_request.id,
      'created_at', existing_request.created_at,
      'existing_link', true
    );
  end if;

  insert into public.family_link_requests (
    child_id, child_name, parent_id, parent_name, message
  ) values (
    trim(p_child_id), trim(p_child_name), trim(p_parent_id), trim(p_parent_name), clean_message
  ) returning * into inserted_request;

  return jsonb_build_object(
    'id', inserted_request.id,
    'created_at', inserted_request.created_at,
    'duplicate', false
  );
end;
$$;

create or replace function public.list_family_link_requests()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if auth.uid() is null or not exists (
    select 1 from public.superadmins s where s.user_id = auth.uid()
  ) then
    raise exception 'Accès réservé au superadmin.' using errcode = '42501';
  end if;

  select coalesce(
    jsonb_agg(
      to_jsonb(r) || jsonb_build_object(
        'additional_reports', coalesce((
          select jsonb_agg(
            jsonb_build_object('id', report.id, 'message', report.message, 'created_at', report.created_at)
            order by report.created_at, report.id
          )
          from public.family_link_request_reports report
          where report.request_id = r.id
        ), '[]'::jsonb)
      )
      order by (r.status = 'pending') desc, r.created_at desc
    ),
    '[]'::jsonb
  ) into result
  from public.family_link_requests r;

  return result;
end;
$$;

create or replace function public.claim_family_link_request_report_email(p_report_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed_report public.family_link_request_reports%rowtype;
  emails_in_window integer;
  result jsonb;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Accès réservé au service d’envoi.' using errcode = '42501';
  end if;

  update public.family_link_request_reports report
    set email_claimed_at = now()
    where report.id = p_report_id
      and report.email_sent_at is null
      and (report.email_claimed_at is null or report.email_claimed_at < now() - interval '10 minutes')
    returning * into claimed_report;

  if not found then
    return null;
  end if;

  insert into public.family_link_request_email_rate_limit as limits (
    id, window_started_at, sent_count
  ) values (true, now(), 1)
  on conflict (id) do update
    set window_started_at = case
          when limits.window_started_at <= now() - interval '1 hour' then now()
          else limits.window_started_at
        end,
        sent_count = case
          when limits.window_started_at <= now() - interval '1 hour' then 1
          else limits.sent_count + 1
        end
  returning sent_count into emails_in_window;

  if emails_in_window > 10 then
    update public.family_link_request_reports report
      set email_claimed_at = null
      where report.id = p_report_id and report.email_sent_at is null;
    raise exception 'Limite horaire de notifications atteinte.' using errcode = 'P0001';
  end if;

  select jsonb_build_object(
    'id', claimed_report.id,
    'request_id', claimed_report.request_id,
    'message', claimed_report.message,
    'created_at', claimed_report.created_at,
    'child_name', request.child_name,
    'parent_name', request.parent_name
  ) into result
  from public.family_link_requests request
  where request.id = claimed_report.request_id;

  return result;
end;
$$;

create or replace function public.mark_family_link_request_report_email_sent(p_report_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Accès réservé au service d’envoi.' using errcode = '42501';
  end if;

  update public.family_link_request_reports report
    set email_sent_at = now(), email_claimed_at = null
    where report.id = p_report_id
      and report.email_sent_at is null
      and report.email_claimed_at is not null;

  return found;
end;
$$;

create or replace function public.release_family_link_request_report_email(p_report_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Accès réservé au service d’envoi.' using errcode = '42501';
  end if;

  update public.family_link_request_reports report
    set email_claimed_at = null
    where report.id = p_report_id and report.email_sent_at is null;

  return found;
end;
$$;

revoke all on function public.submit_family_link_request(text, text, text, text, text) from public;
revoke all on function public.submit_family_link_request(text, text, text, text, text) from anon;
grant execute on function public.submit_family_link_request(text, text, text, text, text) to anon, authenticated;
revoke all on function public.list_family_link_requests() from public;
revoke all on function public.list_family_link_requests() from anon;
grant execute on function public.list_family_link_requests() to authenticated;

revoke all on function public.claim_family_link_request_report_email(bigint) from public, anon, authenticated;
revoke all on function public.mark_family_link_request_report_email_sent(bigint) from public, anon, authenticated;
revoke all on function public.release_family_link_request_report_email(bigint) from public, anon, authenticated;
grant execute on function public.claim_family_link_request_report_email(bigint) to service_role;
grant execute on function public.mark_family_link_request_report_email_sent(bigint) to service_role;
grant execute on function public.release_family_link_request_report_email(bigint) to service_role;

commit;
